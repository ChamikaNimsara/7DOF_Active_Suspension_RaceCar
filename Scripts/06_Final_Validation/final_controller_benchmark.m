%% Final Controller Benchmark
% Passive vs Optimized Skyhook vs Final Tuned LQR

clc;

%% =========================================================
% Project Paths
% ==========================================================

scriptPath = mfilename('fullpath');
scriptFolder = fileparts(scriptPath);
projectFolder = fileparts(fileparts(scriptFolder));

passiveResultsFolder = fullfile(projectFolder, 'Results', 'Passive');
skyhookResultsFolder = fullfile(projectFolder, 'Results', 'Skyhook');
lqrResultsFolder = fullfile(projectFolder, 'Results', 'LQR');
robustnessResultsFolder = fullfile(projectFolder, 'Results', 'Robustness');
operatingResultsFolder = fullfile(projectFolder, 'Results', 'Operating_Envelope');
finalResultsFolder = fullfile(projectFolder, 'Results', 'Final');

resultsFolder = fullfile(projectFolder, 'Results', 'Final');
plotsFolder = fullfile(projectFolder, 'Plots', 'Final');

if ~exist(plotsFolder, 'dir')
    mkdir(plotsFolder);
end

%% =========================================================
% Load Passive Bump Baseline
% ==========================================================

passiveBump = load(fullfile( ...
    passiveResultsFolder, ...
    'passive_baseline_summary.mat'));

%% =========================================================
% Load Optimized Skyhook Bump Results
% ==========================================================

skyhookBump = load(fullfile( ...
    skyhookResultsFolder, ...
    'skyhook_weighted_optimization.mat'));

%% =========================================================
% Load LQR Bump Sweep
% ==========================================================

lqrBump = load(fullfile( ...
    lqrResultsFolder, ...
    'lqr_candidate_bump_sweep.mat'));

bumpTable = ...
    lqrBump.candidateTable;

idxFinal = find( ...
    abs(bumpTable.Ratio - 0.125) < 1e-9, ...
    1);

if isempty(idxFinal)
    error('Final LQR bump candidate not found.');
end

%% =========================================================
% Bump Metrics
% ==========================================================

Controller = { ...
    'Passive'
    'Optimized Skyhook'
    'Final Tuned LQR'};

PeakHeave_mm = [ ...
    passiveBump.peak_heave_mm
    skyhookBump.optimal_peak_heave
    bumpTable.PeakHeave_mm(idxFinal)];

PeakPitch_deg = [ ...
    passiveBump.peak_pitch_deg
    skyhookBump.optimal_peak_pitch
    bumpTable.PeakPitch_deg(idxFinal)];

RMSHeaveAccel = [ ...
    passiveBump.rms_heave_accel
    skyhookBump.optimal_rms_heave_accel
    bumpTable.RMSHeaveAccel_mps2(idxFinal)];

RMSPitchAccel = [ ...
    passiveBump.rms_pitch_accel
    skyhookBump.optimal_rms_pitch_accel
    bumpTable.RMSPitchAccel_degps2(idxFinal)];

SettlingTime = [ ...
    passiveBump.settling_time
    skyhookBump.optimal_settling_time
    bumpTable.SettlingTime_s(idxFinal)];

PeakForce = [ ...
    0
    skyhookBump.optimal_peak_force
    bumpTable.PeakForce_N(idxFinal)];

bumpComparison = table( ...
    Controller, ...
    PeakHeave_mm, ...
    PeakPitch_deg, ...
    RMSHeaveAccel, ...
    RMSPitchAccel, ...
    SettlingTime, ...
    PeakForce);

%% =========================================================
% Load Kerb Results
% ==========================================================

passiveKerb = load(fullfile( ...
    passiveResultsFolder, ...
    'passive_kerb_metrics.mat'));

skyhookKerb = load(fullfile( ...
    skyhookResultsFolder, ...
    'active_vs_passive_kerb_metrics.mat'));

lqrKerb = load(fullfile( ...
    lqrResultsFolder, ...
    'lqr_final_candidate_kerb_sweep.mat'));

kerbTable = ...
    lqrKerb.kerbTable;

idxKerb = find( ...
    abs(kerbTable.Ratio - 0.125) < 1e-9, ...
    1);

%% =========================================================
% Kerb Metrics
% ==========================================================

KerbPeakHeave_mm = [ ...
    passiveKerb.peak_heave_mm
    skyhookKerb.active_peak_heave_mm
    kerbTable.PeakHeave_mm(idxKerb)];

KerbPeakPitch_deg = [ ...
    passiveKerb.peak_pitch_deg
    skyhookKerb.active_peak_pitch_deg
    kerbTable.PeakPitch_deg(idxKerb)];

KerbPeakRoll_deg = [ ...
    passiveKerb.peak_roll_deg
    skyhookKerb.active_peak_roll_deg
    kerbTable.PeakRoll_deg(idxKerb)];

KerbRMSHeaveAccel = [ ...
    passiveKerb.rms_heave_accel
    skyhookKerb.active_rms_heave_accel
    kerbTable.RMSHeaveAccel_mps2(idxKerb)];

KerbRMSPitchAccel = [ ...
    passiveKerb.rms_pitch_accel
    skyhookKerb.active_rms_pitch_accel
    kerbTable.RMSPitchAccel_degps2(idxKerb)];

KerbRMSRollAccel = [ ...
    passiveKerb.rms_roll_accel
    skyhookKerb.active_rms_roll_accel
    kerbTable.RMSRollAccel_degps2(idxKerb)];

KerbRollSettling = [ ...
    passiveKerb.roll_settling_time
    skyhookKerb.active_roll_settling_time
    kerbTable.RollSettlingTime_s(idxKerb)];

KerbPeakForce = [ ...
    0
    skyhookKerb.active_peak_force
    kerbTable.PeakForce_N(idxKerb)];

kerbComparison = table( ...
    Controller, ...
    KerbPeakHeave_mm, ...
    KerbPeakPitch_deg, ...
    KerbPeakRoll_deg, ...
    KerbRMSHeaveAccel, ...
    KerbRMSPitchAccel, ...
    KerbRMSRollAccel, ...
    KerbRollSettling, ...
    KerbPeakForce);

%% =========================================================
% Display
% ==========================================================

disp('====================================================')
disp('FINAL CONTROLLER BENCHMARK')
disp('====================================================')

disp(' ')
disp('SYMMETRIC BUMP')
disp(bumpComparison)

disp(' ')
disp('ASYMMETRIC KERB')
disp(kerbComparison)

%% =========================================================
% Save CSV Files
% ==========================================================

bumpCSV = fullfile( ...
    resultsFolder, ...
    'final_bump_controller_comparison.csv');

kerbCSV = fullfile( ...
    resultsFolder, ...
    'final_kerb_controller_comparison.csv');

writetable( ...
    bumpComparison, ...
    bumpCSV);

writetable( ...
    kerbComparison, ...
    kerbCSV);

%% =========================================================
% Save MAT
% ==========================================================

matFile = fullfile( ...
    resultsFolder, ...
    'final_controller_benchmark.mat');

save(matFile, ...
    'bumpComparison', ...
    'kerbComparison');

%% =========================================================
% Save TXT
% ==========================================================

txtFile = fullfile( ...
    resultsFolder, ...
    'final_controller_benchmark.txt');

fid = fopen(txtFile, 'w');

fprintf(fid, ...
    'FINAL ACTIVE SUSPENSION CONTROLLER BENCHMARK\n');

fprintf(fid, ...
    '============================================\n\n');

fprintf(fid, ...
    'Final tuned LQR Q/R ratio = 0.125\n\n');

fprintf(fid, ...
    'SYMMETRIC BUMP\n');

fprintf(fid, ...
    '--------------------------------------------\n');

for i = 1:3

    fprintf(fid, ...
        '%s\n', ...
        Controller{i});

    fprintf(fid, ...
        'Peak heave = %.4f mm\n', ...
        PeakHeave_mm(i));

    fprintf(fid, ...
        'Peak pitch = %.5f deg\n', ...
        PeakPitch_deg(i));

    fprintf(fid, ...
        'RMS heave accel = %.5f m/s^2\n', ...
        RMSHeaveAccel(i));

    fprintf(fid, ...
        'RMS pitch accel = %.5f deg/s^2\n', ...
        RMSPitchAccel(i));

    fprintf(fid, ...
        'Settling time = %.3f s\n', ...
        SettlingTime(i));

    fprintf(fid, ...
        'Peak actuator force = %.2f N\n\n', ...
        PeakForce(i));

end

fprintf(fid, ...
    '\nASYMMETRIC KERB\n');

fprintf(fid, ...
    '--------------------------------------------\n');

for i = 1:3

    fprintf(fid, ...
        '%s\n', ...
        Controller{i});

    fprintf(fid, ...
        'Peak heave = %.4f mm\n', ...
        KerbPeakHeave_mm(i));

    fprintf(fid, ...
        'Peak pitch = %.5f deg\n', ...
        KerbPeakPitch_deg(i));

    fprintf(fid, ...
        'Peak roll = %.5f deg\n', ...
        KerbPeakRoll_deg(i));

    fprintf(fid, ...
        'RMS heave accel = %.5f m/s^2\n', ...
        KerbRMSHeaveAccel(i));

    fprintf(fid, ...
        'RMS pitch accel = %.5f deg/s^2\n', ...
        KerbRMSPitchAccel(i));

    fprintf(fid, ...
        'RMS roll accel = %.5f deg/s^2\n', ...
        KerbRMSRollAccel(i));

    fprintf(fid, ...
        'Roll settling = %.3f s\n', ...
        KerbRollSettling(i));

    fprintf(fid, ...
        'Peak actuator force = %.2f N\n\n', ...
        KerbPeakForce(i));

end

fclose(fid);

%% =========================================================
% Bump Normalized Comparison
% ==========================================================

bumpNormalized = [ ...
    100*PeakHeave_mm/passiveBump.peak_heave_mm, ...
    100*PeakPitch_deg/passiveBump.peak_pitch_deg, ...
    100*RMSHeaveAccel/passiveBump.rms_heave_accel, ...
    100*RMSPitchAccel/passiveBump.rms_pitch_accel, ...
    100*SettlingTime/passiveBump.settling_time];

fig1 = figure( ...
    'Name', ...
    'Final Bump Controller Benchmark', ...
    'NumberTitle', ...
    'off');

bar( ...
    categorical(Controller), ...
    bumpNormalized);

grid on

ylabel('Metric [% of Passive]')

title('Final Controller Benchmark - Symmetric Bump')

legend( ...
    'Peak Heave', ...
    'Peak Pitch', ...
    'RMS Heave Accel', ...
    'RMS Pitch Accel', ...
    'Settling Time', ...
    'Location', ...
    'bestoutside');

bumpPNG = fullfile( ...
    plotsFolder, ...
    'final_controller_bump_benchmark.png');

bumpFIG = fullfile( ...
    plotsFolder, ...
    'final_controller_bump_benchmark.fig');

exportgraphics( ...
    fig1, ...
    bumpPNG, ...
    'Resolution', 300);

savefig(fig1, bumpFIG);

%% =========================================================
% Kerb Normalized Comparison
% ==========================================================

kerbNormalized = [ ...
    100*KerbPeakHeave_mm/passiveKerb.peak_heave_mm, ...
    100*KerbPeakPitch_deg/passiveKerb.peak_pitch_deg, ...
    100*KerbPeakRoll_deg/passiveKerb.peak_roll_deg, ...
    100*KerbRMSHeaveAccel/passiveKerb.rms_heave_accel, ...
    100*KerbRMSPitchAccel/passiveKerb.rms_pitch_accel, ...
    100*KerbRMSRollAccel/passiveKerb.rms_roll_accel, ...
    100*KerbRollSettling/passiveKerb.roll_settling_time];

fig2 = figure( ...
    'Name', ...
    'Final Kerb Controller Benchmark', ...
    'NumberTitle', ...
    'off');

bar( ...
    categorical(Controller), ...
    kerbNormalized);

grid on

ylabel('Metric [% of Passive]')

title('Final Controller Benchmark - Asymmetric Kerb')

legend( ...
    'Peak Heave', ...
    'Peak Pitch', ...
    'Peak Roll', ...
    'RMS Heave Accel', ...
    'RMS Pitch Accel', ...
    'RMS Roll Accel', ...
    'Roll Settling', ...
    'Location', ...
    'bestoutside');

kerbPNG = fullfile( ...
    plotsFolder, ...
    'final_controller_kerb_benchmark.png');

kerbFIG = fullfile( ...
    plotsFolder, ...
    'final_controller_kerb_benchmark.fig');

exportgraphics( ...
    fig2, ...
    kerbPNG, ...
    'Resolution', 300);

savefig(fig2, kerbFIG);

%% =========================================================
% Actuator Comparison
% ==========================================================

fig3 = figure( ...
    'Name', ...
    'Final Actuator Effort Comparison', ...
    'NumberTitle', ...
    'off');

X = categorical({ ...
    'Symmetric Bump', ...
    'Asymmetric Kerb'});

forceData = [ ...
    skyhookBump.optimal_peak_force, ...
    bumpTable.PeakForce_N(idxFinal); ...
    skyhookKerb.active_peak_force, ...
    kerbTable.PeakForce_N(idxKerb)];

bar(X, forceData);

hold on

yline( ...
    3000, ...
    '--');

grid on

ylabel('Peak Actuator Force [N]')

title('Optimized Skyhook vs Tuned LQR - Actuator Demand')

legend( ...
    'Optimized Skyhook', ...
    'Tuned LQR', ...
    'Actuator Limit', ...
    'Location', ...
    'best');

forcePNG = fullfile( ...
    plotsFolder, ...
    'final_controller_actuator_comparison.png');

forceFIG = fullfile( ...
    plotsFolder, ...
    'final_controller_actuator_comparison.fig');

exportgraphics( ...
    fig3, ...
    forcePNG, ...
    'Resolution', 300);

savefig(fig3, forceFIG);

%% =========================================================
% Confirmation
% ==========================================================

disp(' ')
disp('Final controller benchmark saved successfully.');

fprintf('\nResults:\n');
fprintf('%s\n', txtFile);
fprintf('%s\n', bumpCSV);
fprintf('%s\n', kerbCSV);
fprintf('%s\n', matFile);

fprintf('\nPlots:\n');
fprintf('%s\n', bumpPNG);
fprintf('%s\n', kerbPNG);
fprintf('%s\n', forcePNG);
