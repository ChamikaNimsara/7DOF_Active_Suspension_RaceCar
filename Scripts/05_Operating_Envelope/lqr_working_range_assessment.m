%% Final Tuned LQR - Working Range Assessment
% Evaluates:
% - Suspension deflection
% - Suspension relative velocity
% - Tyre deflection
% - Tyre normal-load/contact condition
% - Actuator loading
%
% Operating condition:
% 144 km/h asymmetric left-side kerb

clear;
clc;

%% =========================================================
% Vehicle Parameters
% ==========================================================

run(fullfile(fileparts(fileparts(fileparts(mfilename('fullpath')))), ...
    'Scripts', '01_Parameters', 'vehicle_parameters.m'));

%% =========================================================
% Project Paths
% ==========================================================

scriptPath = mfilename('fullpath');
scriptFolder = fileparts(scriptPath);
projectFolder = fileparts(fileparts(scriptFolder));

passiveResultsFolder = fullfile(projectFolder, 'Results', 'Passive');
skyhookResultsFolder = fullfile(projectFolder, 'Results', 'Skyhook');
lqrResultsFolder = fullfile(projectFolder, 'Results', 'LQR');
robustnessResultsFolder = fullfile(projectFolder, 'Results', 'Robustness');
operatingResultsFolder = fullfile(projectFolder, 'Results', 'Operating_Envelope');
finalResultsFolder = fullfile(projectFolder, 'Results', 'Final');

resultsFolder = fullfile(projectFolder, 'Results', 'Operating_Envelope');
plotsFolder = fullfile(projectFolder, 'Plots', 'Operating_Envelope');

if ~exist(plotsFolder, 'dir')
    mkdir(plotsFolder);
end

%% =========================================================
% Load Final Tuned LQR
% ==========================================================

controllerFile = fullfile( ...
    lqrResultsFolder, ...
    'final_tuned_lqr_controller.mat');

if ~isfile(controllerFile)
    error('final_tuned_lqr_controller.mat not found.');
end

controllerData = load(controllerFile);

K_lqr = controllerData.K_lqr_final;

active_mode = 1;
F_act_max = 3000;

%% =========================================================
% High-Speed Kerb Operating Point
% ==========================================================

V = 40;                  % [m/s] = 144 km/h

kerb_duration = ...
    kerb_length / V;

rear_delay = ...
    L / V;

t_kerb_rear = ...
    t_kerb_front + rear_delay;

%% =========================================================
% Push Variables to Simulink
% ==========================================================

assignin('base','V',V);

assignin( ...
    'base', ...
    'kerb_duration', ...
    kerb_duration);

assignin( ...
    'base', ...
    'rear_delay', ...
    rear_delay);

assignin( ...
    'base', ...
    't_kerb_rear', ...
    t_kerb_rear);

assignin( ...
    'base', ...
    'K_lqr', ...
    K_lqr);

assignin( ...
    'base', ...
    'active_mode', ...
    active_mode);

assignin( ...
    'base', ...
    'F_act_max', ...
    F_act_max);

%% =========================================================
% Model
% ==========================================================

modelName = ...
    'RaceCar_7DOF_ActiveSuspension';

modelFile = fullfile( ...
    projectFolder, ...
    'Model', ...
    [modelName '.slx']);

if ~isfile(modelFile)
    error('Simulink model not found: %s', modelFile);
end

load_system(modelFile);

%% =========================================================
% Simulate
% ==========================================================

disp('====================================================')
disp('LQR WORKING-RANGE ASSESSMENT - 144 km/h KERB')
disp('====================================================')

simOut = sim( ...
    modelName, ...
    'StopTime', ...
    '5', ...
    'ReturnWorkspaceOutputs', ...
    'on');

%% =========================================================
% Signals
% ==========================================================

zs = getLoggedSignal( ...
    simOut, ...
    'z_s_out');

theta = getLoggedSignal( ...
    simOut, ...
    'theta_out');

phi = getLoggedSignal( ...
    simOut, ...
    'phi_out');

zsDot = getLoggedSignal( ...
    simOut, ...
    'z_s_dot');

thetaDot = getLoggedSignal( ...
    simOut, ...
    'theta_dot');

phiDot = getLoggedSignal( ...
    simOut, ...
    'phi_dot');

zuFL = getLoggedSignal( ...
    simOut, ...
    'z_u_FL_out');

zuFR = getLoggedSignal( ...
    simOut, ...
    'z_u_FR_out');

zuRL = getLoggedSignal( ...
    simOut, ...
    'z_u_RL_out');

zuRR = getLoggedSignal( ...
    simOut, ...
    'z_u_RR_out');

zuFLDot = getLoggedSignal( ...
    simOut, ...
    'z_u_FL_dot');

zuFRDot = getLoggedSignal( ...
    simOut, ...
    'z_u_FR_dot');

zuRLDot = getLoggedSignal( ...
    simOut, ...
    'z_u_RL_dot');

zuRRDot = getLoggedSignal( ...
    simOut, ...
    'z_u_RR_dot');

FLforce = getLoggedSignal( ...
    simOut, ...
    'F_act_FL_out');

FRforce = getLoggedSignal( ...
    simOut, ...
    'F_act_FR_out');

RLforce = getLoggedSignal( ...
    simOut, ...
    'F_act_RL_out');

RRforce = getLoggedSignal( ...
    simOut, ...
    'F_act_RR_out');

%% =========================================================
% Time
% ==========================================================

t = zs.Time;

%% =========================================================
% Body Corner Displacements
% ==========================================================
%
% Internal angular states are radians.
%
% FL = z_s + a*theta + tf/2*phi
% FR = z_s + a*theta - tf/2*phi
% RL = z_s - b*theta + tr/2*phi
% RR = z_s - b*theta - tr/2*phi

zBodyFL = ...
      zs.Data ...
    + a * theta.Data ...
    + (t_f/2) * phi.Data;

zBodyFR = ...
      zs.Data ...
    + a * theta.Data ...
    - (t_f/2) * phi.Data;

zBodyRL = ...
      zs.Data ...
    - b * theta.Data ...
    + (t_r/2) * phi.Data;

zBodyRR = ...
      zs.Data ...
    - b * theta.Data ...
    - (t_r/2) * phi.Data;

%% =========================================================
% Body Corner Velocities
% ==========================================================

zBodyDotFL = ...
      zsDot.Data ...
    + a * thetaDot.Data ...
    + (t_f/2) * phiDot.Data;

zBodyDotFR = ...
      zsDot.Data ...
    + a * thetaDot.Data ...
    - (t_f/2) * phiDot.Data;

zBodyDotRL = ...
      zsDot.Data ...
    - b * thetaDot.Data ...
    + (t_r/2) * phiDot.Data;

zBodyDotRR = ...
      zsDot.Data ...
    - b * thetaDot.Data ...
    - (t_r/2) * phiDot.Data;

%% =========================================================
% Suspension Deflections
% ==========================================================

deltaFL = ...
    zBodyFL - zuFL.Data;

deltaFR = ...
    zBodyFR - zuFR.Data;

deltaRL = ...
    zBodyRL - zuRL.Data;

deltaRR = ...
    zBodyRR - zuRR.Data;

%% =========================================================
% Suspension Relative Velocities
% ==========================================================

deltaDotFL = ...
    zBodyDotFL - zuFLDot.Data;

deltaDotFR = ...
    zBodyDotFR - zuFRDot.Data;

deltaDotRL = ...
    zBodyDotRL - zuRLDot.Data;

deltaDotRR = ...
    zBodyDotRR - zuRRDot.Data;

%% =========================================================
% Reconstruct Road Inputs
% ==========================================================
%
% Left-side kerb:
% FL and RL excited
% FR and RR remain flat

zrFL = zeros(size(t));
zrFR = zeros(size(t));
zrRL = zeros(size(t));
zrRR = zeros(size(t));

frontMask = ...
    (t >= t_kerb_front) & ...
    (t <= t_kerb_front + kerb_duration);

rearMask = ...
    (t >= t_kerb_rear) & ...
    (t <= t_kerb_rear + kerb_duration);

% Half-sine front-left kerb
zrFL(frontMask) = ...
    kerb_height .* ...
    sin( ...
        pi .* ...
        (t(frontMask) - t_kerb_front) ./ ...
        kerb_duration);

% Half-sine rear-left kerb
zrRL(rearMask) = ...
    kerb_height .* ...
    sin( ...
        pi .* ...
        (t(rearMask) - t_kerb_rear) ./ ...
        kerb_duration);

%% =========================================================
% Tyre Deflections
% ==========================================================
%
% Positive tyreDef means wheel centre is above road
% relative to equilibrium coordinate convention.

tyreDefFL = ...
    zuFL.Data - zrFL;

tyreDefFR = ...
    zuFR.Data - zrFR;

tyreDefRL = ...
    zuRL.Data - zrRL;

tyreDefRR = ...
    zuRR.Data - zrRR;

%% =========================================================
% Corner Labels
% ==========================================================

cornerNames = { ...
    'FL'; ...
    'FR'; ...
    'RL'; ...
    'RR'};

%% =========================================================
% Working-Range Peak Metrics
% ==========================================================

PeakSuspDeflection_mm = 1000 * [ ...
    max(abs(deltaFL)); ...
    max(abs(deltaFR)); ...
    max(abs(deltaRL)); ...
    max(abs(deltaRR))];

PeakSuspVelocity_mps = [ ...
    max(abs(deltaDotFL)); ...
    max(abs(deltaDotFR)); ...
    max(abs(deltaDotRL)); ...
    max(abs(deltaDotRR))];

PeakTyreDeflection_mm = 1000 * [ ...
    max(abs(tyreDefFL)); ...
    max(abs(tyreDefFR)); ...
    max(abs(tyreDefRL)); ...
    max(abs(tyreDefRR))];

PeakActuatorForce_N = [ ...
    max(abs(FLforce.Data)); ...
    max(abs(FRforce.Data)); ...
    max(abs(RLforce.Data)); ...
    max(abs(RRforce.Data))];

ActuatorUtilization_pct = ...
    100 * PeakActuatorForce_N / F_act_max;

%% =========================================================
% Working-Range Table
% ==========================================================

workingRangeTable = table( ...
    cornerNames, ...
    PeakSuspDeflection_mm, ...
    PeakSuspVelocity_mps, ...
    PeakTyreDeflection_mm, ...
    PeakActuatorForce_N, ...
    ActuatorUtilization_pct, ...
    'VariableNames', { ...
    'Corner', ...
    'PeakSuspDeflection_mm', ...
    'PeakSuspVelocity_mps', ...
    'PeakTyreDeflection_mm', ...
    'PeakActuatorForce_N', ...
    'ActuatorUtilization_pct'});

%% =========================================================
% Tyre Contact / Normal Load Check
% ==========================================================
%
% Model is linearized around static equilibrium.
%
% Total tyre normal load:
%
% Fz = Fz_static - k_t * (z_u - z_r)
%
% A negative Fz indicates the linear tyre spring is
% predicting tensile force, which physically means the
% tyre would have unloaded / lost road contact.

Fz0_FL = F_FL_static;
Fz0_FR = F_FR_static;
Fz0_RL = F_RL_static;
Fz0_RR = F_RR_static;

Fz_FL = ...
    Fz0_FL - k_t * tyreDefFL;

Fz_FR = ...
    Fz0_FR - k_t * tyreDefFR;

Fz_RL = ...
    Fz0_RL - k_t * tyreDefRL;

Fz_RR = ...
    Fz0_RR - k_t * tyreDefRR;

%% =========================================================
% Tyre Load Metrics
% ==========================================================

MinFz_N = [ ...
    min(Fz_FL); ...
    min(Fz_FR); ...
    min(Fz_RL); ...
    min(Fz_RR)];

MaxFz_N = [ ...
    max(Fz_FL); ...
    max(Fz_FR); ...
    max(Fz_RL); ...
    max(Fz_RR)];

ContactLoss_pct = 100 * [ ...
    mean(Fz_FL <= 0); ...
    mean(Fz_FR <= 0); ...
    mean(Fz_RL <= 0); ...
    mean(Fz_RR <= 0)];

tyreContactTable = table( ...
    cornerNames, ...
    MinFz_N, ...
    MaxFz_N, ...
    ContactLoss_pct, ...
    'VariableNames', { ...
    'Corner', ...
    'MinimumNormalLoad_N', ...
    'MaximumNormalLoad_N', ...
    'ContactLoss_pct'});

