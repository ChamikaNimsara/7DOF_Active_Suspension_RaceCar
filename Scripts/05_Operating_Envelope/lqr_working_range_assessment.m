%% =========================================================
% Helper Function
% IMPORTANT:
% Local functions must remain at the END of this script.
% ==========================================================

function sig = getLoggedSignal(simOut,signalName)

    try

        sig = simOut.get(signalName);

        if ~isempty(sig)
            return;
        end

    catch
    end

    if evalin( ...
            'base', ...
            sprintf( ...
                'exist(''%s'',''var'')', ...
                signalName))

        sig = evalin( ...
            'base', ...
            signalName);

        return;

    end

    error( ...
        'Unable to locate logged signal: %s', ...
        signalName);

end
