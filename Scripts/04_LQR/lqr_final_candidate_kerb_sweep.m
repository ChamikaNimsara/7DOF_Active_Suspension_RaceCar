for k = 1:nCases

    fprintf(fid, ...
        'Q/R ratio = %.3f\n', ...
        Ratio(k));

    fprintf(fid, ...
        'Peak heave = %.5f mm\n', ...
        PeakHeave_mm(k));

    fprintf(fid, ...
        'Peak pitch = %.6f deg\n', ...
        PeakPitch_deg(k));

    fprintf(fid, ...
        'Peak roll = %.6f deg\n', ...
        PeakRoll_deg(k));

    fprintf(fid, ...
        'RMS heave accel = %.6f m/s^2\n', ...
        RMSHeaveAccel_mps2(k));

    fprintf(fid, ...
        'RMS pitch accel = %.6f deg/s^2\n', ...
        RMSPitchAccel_degps2(k));

    fprintf(fid, ...
        'RMS roll accel = %.6f deg/s^2\n', ...
        RMSRollAccel_degps2(k));

    fprintf(fid, ...
        'Roll settling = %.6f s\n', ...
        RollSettlingTime_s(k));

    fprintf(fid, ...
        'Peak force = %.2f N\n', ...
        PeakForce_N(k));

    fprintf(fid, ...
        'Bump objective = %.6f\n', ...
        bumpScore(k));

    fprintf(fid, ...
        'Kerb objective = %.6f\n', ...
        kerbScore(k));

    fprintf(fid, ...
        'Combined objective = %.6f\n\n', ...
        combinedScore(k));

end

fprintf(fid, ...
    'FINAL Q/R RATIO = %.3f\n', ...
    finalRatio);

fprintf(fid, ...
    'FINAL COMBINED OBJECTIVE = %.6f\n', ...
    bestCombinedScore);

fclose(fid);


%% =========================================================
